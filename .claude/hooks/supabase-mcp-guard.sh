#!/usr/bin/env bash
# PreToolUse(mcp__.*) guard — see CLAUDE.md / AGENTS.md RULE 0.
#
# Production may be READ through one MCP server, `supabase-prod-ro` (.mcp.json:
# Supabase's hosted MCP with read_only=true, scoped to this project). It is
# never written by any agent: every change to data or structure goes out as a
# migration file the owner applies by hand.
#
#   mcp__claude_ai_Supabase__*  (account-wide claude.ai connector,
#                                write tools included)                   -> deny
#   mcp__supabase-prod-ro__<read tool>                                   -> allow
#   mcp__supabase-prod-ro__execute_sql with a statement that writes      -> deny
#   mcp__supabase-prod-ro__<anything else, incl. tools added later>      -> deny
#   every other MCP tool                                                 -> fall through
#
# The SQL check is a second layer, not the first: read_only=true makes the
# server run every query as a read-only Postgres user, and that is what holds.
# This catches a write before it is even sent, and keeps the rule if the URL
# in .mcp.json is ever edited. A deny is the rule working — do not rephrase the
# query to slip past it and do not edit this file to get a task done; say so
# and let the owner decide.

input=$(cat)
tool=$(printf '%s' "$input" | jq -r '.tool_name // ""')

decide() {
  jq -nc --arg d "$1" --arg r "$2" \
    '{hookSpecificOutput:{hookEventName:"PreToolUse",permissionDecision:$d,permissionDecisionReason:$r}}'
  exit 0
}

case "$tool" in
  mcp__claude_ai_Supabase__*)
    decide deny "The claude.ai Supabase connector reaches every project on the account and can write. In this project production is read only through the supabase-prod-ro MCP server (RULE 0)."
    ;;
  mcp__supabase-prod-ro__*) ;;
  *) exit 0 ;;
esac

name=${tool#mcp__supabase-prod-ro__}

case "$name" in
  list_tables | list_extensions | list_migrations | get_logs | get_advisors | \
    search_docs | generate_typescript_types | get_project_url | \
    list_edge_functions | get_edge_function | list_storage_buckets | \
    get_storage_config | list_branches)
    decide allow "Read-only call on the production project through supabase-prod-ro (RULE 0)."
    ;;
  execute_sql) ;;
  *)
    decide deny "'$name' is not a read tool. Production is never changed by an agent — write a migration in supabase/migrations/ for the owner to apply (RULE 0)."
    ;;
esac

query=$(printf '%s' "$input" | jq -r '.tool_input.query // ""')

# Comments and string literals are not statements: strip them, then lowercase.
# A statement that writes is refused wherever it sits — first, after a `;`, or
# inside a CTE (`with x as (delete from …)`).
verdict=$(printf '%s' "$query" | perl -0777 -ne '
  s{/\*.*?\*/}{ }gs;          # block comments
  s{--[^\n]*}{ }g;            # line comments
  s{\$([A-Za-z_]*)\$.*?\$\1\$}{ }gs;  # dollar-quoted bodies
  s{\x27(?:[^\x27]|\x27\x27)*\x27}{ }g;  # string literals
  $_ = lc $_;
  my $start = qr/(?:^|;)\s*(insert|update|delete|merge|upsert|drop|alter|create|truncate|grant|revoke|comment|copy|vacuum|analyze|reindex|cluster|refresh|lock|call|do|set|reset|begin|start|commit|end|rollback|abort|savepoint|release|discard|security|load|import|prepare|execute|listen|notify|unlisten)\b/;
  if (/$start/) { print "statement:$1"; exit }
  if (/\b(insert\s+into|delete\s+from|merge\s+into|update\s+[\w."]+\s+set)\b/) { print "write:$1"; exit }
  if (/\bselect\b[^;]*?\binto\s+(?!strict\b)[\w."]+/ && !/\binsert\s+into\b/) { print "select-into"; exit }
  print "ok";
')

if [ "$verdict" != "ok" ]; then
  decide deny "That SQL writes or controls the session ($verdict). Production is read only — put the change in a new supabase/migrations/ file for the owner to apply (RULE 0)."
fi
decide allow "Read-only query on the production project through supabase-prod-ro (RULE 0)."
